import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8');
assert(html.includes('<title>MURDILIMAX Recovery'));
assert(html.includes('rel="canonical" href="https://murdilimax.com/"'));
assert(!/murdilimax-browser\.hatchable|антидетект|BROWSER STUDIO|cenaradar\.online/i.test(html));
const ids=new Set([...html.matchAll(/\bid=["']([^"']+)["']/g)].map(m=>m[1]));
for(const m of html.matchAll(/href=["']#([^"']+)["']/g)) assert(ids.has(m[1]),'Missing anchor '+m[1]);
for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(m[1]);
const links=[...html.matchAll(/href=["']([^"']+)["']/g)].map(m=>m[1]);
const installers=links.filter(s=>s.includes('/releases/download/'));
assert(installers.length>=3);
assert(installers.every(s=>s==='https://github.com/virus53111/dogizen/releases/download/v0.10.7/MURDILIMAX-Recovery-Setup-0.10.7.exe'));
assert(fs.readFileSync('CNAME','utf8').trim()==='murdilimax.com');
assert(fs.readFileSync('robots.txt','utf8').includes('Sitemap: https://murdilimax.com/sitemap.xml'));
assert(fs.readFileSync('sitemap.xml','utf8').includes('<loc>https://murdilimax.com/</loc>'));
assert(!fs.existsSync('browser'));
assert(!fs.existsSync('account.html'));
console.log('Recovery website: inline JS, anchors, installer links, metadata and retired browser checks passed.');
