          "Sunny days followed by cool, non-freezing nights can favour bright colours. Severe drought can instead cause early leaf loss, while early frost, heavy rain and wind can shorten the display. Peak colour cannot reliably be promised for the same calendar date every year. Tree species, location and the season’s weather all matter."
