function distanceKm(a, b) {
  const radians = Math.PI / 180;
  const dLat = (b[2] - a[2]) * radians;
  const dLon = (b[3] - a[3]) * radians;
  const h = Math.sin(dLat / 2) ** 2 +
    Math.cos(a[2] * radians) * Math.cos(b[2] * radians) * Math.sin(dLon / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.sqrt(h));
}

export function cityNamesInRange(city, radius) {
  const origin = cities.find(([ru, lv]) => city === ru || city === lv);
  if (!origin) return [city];
  const nearby = ['25', '50'].includes(radius)
    ? cities.filter(other => distanceKm(origin, other) <= Number(radius))
    : [origin];
  return nearby.flatMap(([ru, lv]) => [ru, lv]);
}
